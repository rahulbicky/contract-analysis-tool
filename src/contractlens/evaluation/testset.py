def get_test_cases(
    difficulty: str = None,
    category: str = None
) -> list[dict]:
    """
    Filter test cases by difficulty or category.
    """
    cases = TEST_CASES

    if difficulty:
        cases = [c for c in cases if c["difficulty"] == difficulty]
    if category:
        cases = [c for c in cases if c["category"] == category]

    return cases


def get_stats():
    """
    Print test set statistics.
    """
    total = len(TEST_CASES)
    by_difficulty = {}
    by_category = {}

    for tc in TEST_CASES:
        d = tc["difficulty"]
        c = tc["category"]
        by_difficulty[d] = by_difficulty.get(d, 0) + 1
        by_category[c] = by_category.get(c, 0) + 1

    logger.info(f"\nTest Set Statistics")
    logger.info(f"{'='*40}")
    logger.info(f"Total cases: {total}")
    logger.info(f"\nBy difficulty:")
    for d, count in sorted(by_difficulty.items()):
        logger.info(f"  {d}: {count}")
    logger.info(f"\nBy category:")
    for c, count in sorted(by_category.items()):
        logger.info(f"  {c}: {count}")


